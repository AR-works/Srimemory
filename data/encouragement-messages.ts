const LAST_MESSAGE_KEY = 's_bday_last_encouragement_id';

/**
 * Returns an encouragement message, avoiding immediate repetition of the previous message.
 */
export function getRotatingEncouragementMessage(previousId?: number): EncouragementMessage {
  const lastId =
    previousId ??
    (typeof window !== 'undefined'
      ? parseInt(localStorage.getItem(LAST_MESSAGE_KEY) || '-1', 10)
      : -1);

  const available = ENCOURAGEMENT_MESSAGES.filter((msg) => msg.id !== lastId);
  const selected =
    available[Math.floor(Math.random() * available.length)] ||
    ENCOURAGEMENT_MESSAGES[0];

  if (typeof window !== 'undefined') {
    try {
      localStorage.setItem(LAST_MESSAGE_KEY, selected.id.toString());
    } catch {
      // ignore storage errors
    }
  }

  return selected;
}
